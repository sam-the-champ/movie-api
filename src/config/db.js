import { PrismaClient } from "../generated/prisma/client.js"; //importing the prisma client package
import { PrismaPg } from "@prisma/adapter-pg";

const adapter = new PrismaPg({
    connectionString: process.env.DATABASE_URL,
});


const prisma = new PrismaClient({
    log: process.env.NODE_ENV === "development" ? ["query", "info", "warn", "error"]
         : ["error"]            //logging the queries, info, warnings and errors we created a NODE_ENV TO KNOW WHERE WE are
    //whether in development or production and we can use it to log only in development mode
    //the log option is used to log the queries, info, warnings and errors that are generated by the prisma client so that we can 
    // debug our application and see what is going on in the database
}); //creating an instance of the prisma client


const connectDB = async () => {
    try {
        await prisma.$connect(); //connecting to the database 
        console.log("Database connected successfully");
    } catch (error) {
        console.error(`Database connection failed, error: ${error.message}`); //this shows the error message if the connection to the database fails
        process.exit(1); //exit the process with failure
    }
}

const disconnectDB = async () => {
        await prisma.$disconnect(); //disconnecting from the database
        console.log("Database disconnected successfully");
    }
        

export { prisma, connectDB, disconnectDB }; //exporting the prisma client instance so that we can use it in other parts of our application